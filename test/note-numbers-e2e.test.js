const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { startOidc, createApp, login, Browser, until, freePort } = require('./e2e-harness');

test('numbers survive highest deletion/restart/import, dedupe, saved shows and reset merges', async t => {
    const oidc = await startOidc();
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'note-numbers-'));
    const app = createApp({ issuer: oidc.issuer, sessionsFile: path.join(dir, 'sessions.json'), port: await freePort() });
    let browser;
    t.after(async () => { browser?.close(); await app.stop(); oidc.close(); fs.rmSync(dir, { recursive: true, force: true }); });
    await app.start();
    const cookie = await login(app, oidc, 'alice');
    const connect = async () => {
        browser = new Browser(app, cookie);
        browser.load();
        await until(() => browser.page.socket.connected, 'connected');
    };
    await connect();
    const ack = (event, ...args) => browser.page.socket.timeout(5000).emitWithAck(event, ...args);
    const submit = clientId => ack('note-submit', { clientId, text: clientId, tags: ['lx'], noteNumber: 999 });
    const exported = async () => (await fetch(`http://127.0.0.1:${app.port}/playback/live`, { headers: { cookie } })).json();
    const one = await submit('one');
    const two = await submit('two');
    assert.equal(one.noteNumber, 1);
    assert.equal(two.noteNumber, 2);
    assert.deepEqual(await submit('two'), two);
    browser.page.socket.emit('note-delete', { noteId: two.id });
    await until(async () => (await exported()).notes.length === 1, 'deletion');
    browser.close();
    await app.stop();
    await app.start();
    await connect();
    assert.equal((await submit('three')).noteNumber, 3);
    const snapshot = await exported();
    assert.equal(snapshot.nextNoteNumber, 4);
    const show = await ack('save-show', { name: 'Numbered show' });
    assert.ok(!show.error);
    const shows = await (await fetch(`http://127.0.0.1:${app.port}/shows`, { headers: { cookie } })).json();
    const savedId = Array.isArray(shows) ? shows[0].id : shows.shows[0].id;
    const saved = await (await fetch(`http://127.0.0.1:${app.port}/shows/${savedId}`, { headers: { cookie } })).json();
    assert.equal(saved.nextNoteNumber, 4);
    assert.deepEqual(saved.notes.map(n => n.noteNumber), [1, 3]);
    await ack('reset-all');
    assert.equal((await submit('new-show')).noteNumber, 1);
    const resets = await ack('resets-list');
    const keptId = (Array.isArray(resets) ? resets : resets.resets)[0].id;
    assert.equal((await ack('restore-reset', { id: keptId })).restored, 2);
    const merged = await exported();
    assert.equal(new Set(merged.notes.map(n => n.noteNumber)).size, 3);
    assert.equal(merged.notes.find(n => n.clientId === 'new-show').noteNumber, 1);
    assert.equal((await ack('restore-reset', { id: keptId })).restored, 0);
    assert.equal((await exported()).nextNoteNumber, merged.nextNoteNumber);
    const imported = new Promise(resolve => browser.page.socket.once('import-success', resolve));
    browser.page.socket.emit('import-backup', snapshot);
    await imported;
    assert.deepEqual((await exported()).notes.map(n => n.noteNumber), [1, 3]);
    assert.ok((await submit('after-import')).noteNumber >= merged.nextNoteNumber);
    await ack('reset-all');
    const fresh = await submit('fresh');
    assert.equal(fresh.noteNumber, 1);
    browser.page.socket.emit('note-delete', { noteId: fresh.id });
    await until(async () => (await exported()).notes.length === 0, 'empty show after deletion');
    browser.close();
    await app.stop();
    await app.start();
    await connect();
    assert.equal((await submit('after-empty-restart')).noteNumber, 2);
});
