const test = require('node:test');
const assert = require('node:assert/strict');
const os = require('node:os');
const fs = require('node:fs');
const path = require('node:path');
const { until, freePort, startOidc, createApp, login, Browser } = require('./e2e-harness');
test('mentions retain account identities across reconnect, backups and agreed chat restore', async t => {
    const oidc = await startOidc();
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mentions-e2e-'));
    const app = createApp({ issuer: oidc.issuer, sessionsFile: path.join(dir, 'sessions.json'), port: await freePort() });
    const browsers = [];
    t.after(async () => { browsers.forEach(b => b.close()); await app.stop(); oidc.close(); fs.rmSync(dir, { recursive: true, force: true }); });
    await app.start();
    for (const who of ['alice', 'bob']) browsers.push(new Browser(app, await login(app, oidc, who)));
    const [a,b] = browsers;
    a.load(); b.load();
    await until(() => a.page.log && b.page.log, 'logs');
    const mentions = [{ userId: 'sub-bob', name: 'Bob', start: 0, end: 4 }];
    const note = await new Promise(resolve => a.page.socket.emit('note-submit', { text: '@Bob please check', mentions, userId: 'spoof', tags: ['lx'] }, resolve));
    assert.equal(note.userId, 'sub-alice'); assert.deepEqual(note.mentions, mentions);
    a.page.socket.emit('chat-message', { text: '@Bob please check', mentions, userId: 'spoof' });
    await until(() => b.page.log.length === 1, 'chat');
    assert.equal(b.page.log[0].userId, 'sub-alice'); assert.deepEqual(b.page.log[0].mentions, mentions);
    a.page.socket.emit('comment-submit', { noteId: note.id, text: '@Bob reply', mentions });
    await until(() => fs.existsSync(app.backupsDir) && fs.readdirSync(app.backupsDir).length, 'backup');
    await app.stop(); a.close(); b.close();
    await app.start(); a.load(); b.load();
    await until(() => a.page.log?.length === 1 && b.page.log?.length === 1 && a.page.notes.length === 1, 'restored state');
    assert.deepEqual(a.page.log[0].mentions, mentions);
    assert.deepEqual(a.page.notes[0].mentions, mentions);
    assert.equal(a.page.notes[0].userId, 'sub-alice');
    assert.deepEqual(a.page.notes[0].comments[0].mentions, mentions);
    const again = await new Promise(resolve => a.page.socket.emit('note-submit', { text: '@Bob again', mentions, tags: ['lx'] }, resolve));
    assert.equal(again.userId, note.userId);
});
