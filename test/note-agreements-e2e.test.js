const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { io } = require('socket.io-client');
const { startOidc, createApp, freePort, login, Browser, until } = require('./e2e-harness');

test('authenticated agreements broadcast, ignore spoofed actors and survive save, import and restart', async t => {
    const oidc = await startOidc();
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'agreement-test-'));
    const app = createApp({ issuer: oidc.issuer, sessionsFile: path.join(dir, 'sessions.json'), port: await freePort() });
    const sockets = [];
    t.after(async () => {
        sockets.forEach(s => s.close());
        await app.stop();
        oidc.close();
        fs.rmSync(dir, { recursive: true, force: true });
    });
    await app.start();
    const aliceCookie = await login(app, oidc, 'alice');
    const bobCookie = await login(app, oidc, 'bob');
    function connect(cookie, page = 'main') {
        const socket = io(`http://127.0.0.1:${app.port}`, { extraHeaders: { cookie }, auth: { page } });
        sockets.push(socket);
        const state = { socket, notes: null };
        socket.on('notes-update', notes => { state.notes = notes; });
        socket.on('note-added', note => state.notes.push(note));
        return state;
    }
    const alice = connect(aliceCookie);
    const bob = connect(bobCookie);
    await until(() => alice.notes && bob.notes, 'initial notes');
    const note = await alice.socket.timeout(3000).emitWithAck('note-submit', { text: 'Synthetic cue note', tags: ['lx'], agreements: [{ userId: 'spoof', name: 'Spoof' }] });
    assert.equal(note.agreements, undefined);
    const toggle = (s, extra = {}) => s.timeout(3000).emitWithAck('note-agreement-toggle', { noteId: note.id, ...extra });
    await toggle(bob.socket, { userId: 'sub-alice', name: 'Alice' });
    const expected = [{ userId: 'sub-bob', name: 'bob' }];
    await until(() => alice.notes[0]?.agreements?.length === 1, 'broadcast');
    assert.deepEqual(alice.notes[0].agreements, expected);
    await toggle(bob.socket);
    await until(() => alice.notes[0].agreements.length === 0, 'toggle removal');
    const bobTab = connect(bobCookie);
    await until(() => bobTab.notes, 'second tab');
    await toggle(bobTab.socket);
    assert.deepEqual((await toggle(alice.socket)).agreements.map(p => p.userId), ['sub-bob', 'sub-alice']);
    await toggle(alice.socket);
    const overlay = connect(bobCookie, 'overlay');
    await until(() => overlay.notes, 'overlay');
    assert.ok((await toggle(overlay.socket)).error);
    assert.ok((await bob.socket.timeout(3000).emitWithAck('note-agreement-toggle', null)).error);
    const saved = await alice.socket.timeout(3000).emitWithAck('save-show', { name: 'Agreement test' });
    const get = async url => (await fetch(`http://127.0.0.1:${app.port}${url}`, { headers: { cookie: aliceCookie } })).json();
    const exported = new Promise(resolve => alice.socket.once('export-data', resolve));
    alice.socket.emit('export-request', 'json');
    assert.deepEqual(JSON.parse((await exported).data).notes[0].agreements, expected);
    const show = await get(`/shows/${saved.show.id}`);
    assert.deepEqual(show.notes[0].agreements, expected);
    assert.deepEqual((await get('/playback/live')).notes[0].agreements, expected);
    alice.socket.emit('import-backup', { ...show, notes: [{ ...show.notes[0], agreements: [...expected, ...expected, { userId: '', name: 'Bad' }] }] });
    await until(() => alice.notes[0].agreements.length === 1, 'clean import');
    await app.stop();
    const backup = fs.readdirSync(app.backupsDir).filter(f => f.endsWith('.json')).sort().pop();
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(app.backupsDir, backup))).notes[0].agreements, expected);
    await app.start();
    const restored = connect(bobCookie);
    await until(() => restored.notes?.length, 'restored notes');
    assert.deepEqual(restored.notes[0].agreements, expected);
    assert.deepEqual((await toggle(restored.socket)).agreements, [], 'reconnected identity removes its agreement');
});
